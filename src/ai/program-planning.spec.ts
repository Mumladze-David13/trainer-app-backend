import { equipmentFilterFromText } from './program-planning';

describe('equipmentFilterFromText', () => {
  it.each([
    ['только собственный вес', ['собственный вес']],
    ['тренажёрный зал', ['штанга', 'гантели', 'тренажёр', 'собственный вес', 'эспандер']],
    ['штанга и гантели', ['штанга', 'гантели', 'собственный вес']],
    ['дома с гантелями', ['гантели', 'собственный вес', 'эспандер']],
    ['что-то непонятное', ['штанга', 'гантели', 'тренажёр', 'собственный вес', 'эспандер']],
  ])('%s', (text, expected) => {
    expect(equipmentFilterFromText(text)).toEqual(expected);
  });
});
